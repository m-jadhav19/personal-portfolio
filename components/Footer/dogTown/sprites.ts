/**
 * Pixel-art sprites for the footer "dog town" scene.
 *
 * Each sprite is a list of equal-length strings. Characters map to palette
 * roles: `#` ink, `o` paper (lit pixels), `c` collar accent, `.` transparent.
 */

export type SpriteRows = readonly string[];

export type Sprite = {
  rows: SpriteRows;
  width: number;
  height: number;
};

function sprite(rows: SpriteRows): Sprite {
  const width = rows[0]?.length ?? 0;
  for (const row of rows) {
    if (row.length !== width) {
      throw new Error(`Sprite rows must be equal width: "${row}"`);
    }
  }
  return { rows, width, height: rows.length };
}

